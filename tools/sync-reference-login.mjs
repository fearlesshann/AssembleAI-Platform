import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';

// The immutable example is the sole source of login markup and CSS. The only
// markup changes below bind that form to a real identity provider and replace
// demo-only claims. Run after editing the shared login behaviour/resources.
const source = new URL('../references/ui-v1/', import.meta.url);
const publicRoot = new URL('../apps/portal/public/reference-login/', import.meta.url);
const themeRoot = new URL('../deploy/keycloak/themes/assembleai/login/', import.meta.url);
const resourcesRoot = new URL('resources/', themeRoot);
await mkdir(publicRoot, { recursive: true });
await mkdir(resourcesRoot, { recursive: true });
const html = (await readFile(new URL('index.html', source), 'utf8')).replaceAll('\r\n', '\n');
const begin = html.indexOf('  <div class="login-screen"');
const end = html.indexOf('  <div class="page" id="appShell">', begin);
if (begin < 0 || end < begin) throw new Error('Reference login HTML anchors changed.');
let body = html.slice(begin, end).trimEnd()
  .replaceAll('src="logo.png"', 'src="@@ASSET_BASE@@/logo.png"')
  .replaceAll('preview-shots/', '@@ASSET_BASE@@/')
  .replace('<strong>12</strong> 应用在线 · <strong>3</strong> 厂区 Hybrid · RBAC', '企业 AI 应用平台 · 工厂协作 · RBAC')
  .replace('使用平台账号继续。演示样例填写任意非空账号与密码即可进入。', '使用企业账号登录，访问权限范围内的应用与数据。')
  .replace('id="loginForm" novalidate', 'id="loginForm" action="@@LOGIN_ACTION@@" method="post" novalidate')
  .replace('name="account"', 'name="username" value="@@USERNAME@@"')
  .replace('name="remember"', 'name="rememberMe" @@REMEMBER_CHECKED@@')
  .replace('href="#" id="loginForgot"', 'href="@@FORGOT_HREF@@" id="loginForgot"')
  .replace('id="loginFormError" hidden role="alert"></p>', 'id="loginFormError" @@ERROR_HIDDEN@@ role="alert">@@ERROR@@</p>');
const document = (content, assetBase) => `<!DOCTYPE html>
<html lang="zh-CN" data-theme="dark">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="referrer" content="same-origin" />
  <title>集智 · 登录工作台</title>
  <link rel="icon" type="image/png" href="${assetBase}/logo.png" />
  <script src="${assetBase}/theme-init.js"></script>
  <link rel="stylesheet" href="${assetBase}/login.css" />
</head>
<body>
${content}
  <script type="module" src="${assetBase}/login.js"></script>
</body>
</html>
`;
const fixture = body.replace('    </form>', '      <input type="hidden" name="form_token" value="@@CSRF_TOKEN@@" />\n    </form>');
await writeFile(new URL('login.html', publicRoot), '<!-- Generated by tools/sync-reference-login.mjs; HTML-escape replacement values. -->\n' + document(fixture, '@@ASSET_BASE@@'));

let keycloak = body
  .replaceAll('@@ASSET_BASE@@', '${url.resourcesPath}')
  .replace('@@LOGIN_ACTION@@', '${url.loginAction}')
  .replace('@@USERNAME@@', "${(login.username!'')}")
  .replace('@@REMEMBER_CHECKED@@', '<#if login.rememberMe??>checked</#if>')
  .replace('@@FORGOT_HREF@@', '${url.loginResetCredentialsUrl}')
  .replace('@@ERROR_HIDDEN@@', '<#if !message??>hidden</#if>')
  .replace('@@ERROR@@', '<#if message??>${kcSanitize(message.summary)?no_esc}</#if>')
  .replace('class="login-form-error" id="loginFormError"', 'class="<#if message?? && message.type != "error">login-form-desc<#else>login-form-error</#if>" id="loginFormError"')
  .replace('        <label class="login-field" for="loginAccount">', '        <#if !usernameHidden??>\n        <label class="login-field" for="loginAccount">')
  .replace('        <label class="login-field" for="loginPassword">', '        </#if>\n        <label class="login-field" for="loginPassword">')
  .replace('          <label class="login-check">', '          <#if realm.rememberMe && !usernameHidden??>\n          <label class="login-check">')
  .replace('          <a class="login-link"', '          </#if>\n          <#if realm.resetPasswordAllowed>\n          <a class="login-link"')
  .replace('id="loginForgot" tabindex="0">忘记密码</a>', 'id="loginForgot" tabindex="0">忘记密码</a>\n          </#if>')
  .replace('    </form>', '      <input type="hidden" name="credentialId" <#if auth.selectedCredential?has_content>value="${auth.selectedCredential}"</#if> />\n    </form>');
await writeFile(new URL('login.ftl', themeRoot), '<#ftl output_format="HTML" auto_esc=true>\n<#-- Generated by tools/sync-reference-login.mjs. Native Keycloak credential POST. -->\n' + document(keycloak, '${url.resourcesPath}'));

// Other reachable identity steps retain the same hero/card and reference field
// primitives. Bindings follow Keycloak 26.x base templates; there is no parallel
// password API or browser-auth implementation.
const accountBlock = /        <#if !usernameHidden\?\?>[\s\S]*?        <\/\#if>\n/;
const passwordBlock = /        <label class="login-field" for="loginPassword">[\s\S]*?        <\/label>\n/;
const rowBlock = /        <div class="login-row">[\s\S]*?        <\/div>/;
const credentials = /      <input type="hidden" name="credentialId"[^\n]+\n/;
const heading = (page, title, description) => page
  .replace('登录工作台</span>', `${title}</span>`)
  .replace('使用企业账号登录，访问权限范围内的应用与数据。', description);
const savePage = async (name, page) => writeFile(new URL(name, themeRoot),
  '<#ftl output_format="HTML" auto_esc=true>\n<#-- Generated by tools/sync-reference-login.mjs; shared original login shell. -->\n' + document(page, '${url.resourcesPath}'));
const passwordOnly = heading(keycloak, '确认身份', '请重新输入当前账号的密码，继续访问工作台。')
  .replace(accountBlock, '')
  .replace(rowBlock, '        <div class="login-row"><#if realm.resetPasswordAllowed><a class="login-link" href="${url.loginResetCredentialsUrl}" id="loginForgot">忘记密码</a></#if></div>')
  .replace(credentials, '');
await savePage('login-password.ftl', passwordOnly);
const reset = heading(keycloak, '找回密码', '输入企业账号或邮箱。身份中心会发送密码重置邮件。')
  .replace(accountBlock, match => match.replace('        <#if !usernameHidden??>\n', '').replace('        </#if>\n', '').replace("${(login.username!'')}", "${(auth.attemptedUsername!'')}"))
  .replace(passwordBlock, '')
  .replace(rowBlock, '        <div class="login-row"><a class="login-link" id="backToLogin" href="${url.loginUrl}">返回登录</a></div>')
  .replace('进入工作台</span>', '发送重置邮件</span>')
  .replace(credentials, '');
await savePage('login-reset-password.ftl', reset);
const update = heading(keycloak, '设置新密码', '请输入新密码并再次确认。密码规则由企业身份中心校验。')
  .replace(accountBlock, '')
  .replace(passwordBlock, `        <label class="login-field" for="loginPassword">
          <span class="login-label">新密码</span>
          <input class="login-input" id="loginPassword" name="password-new" type="password" autocomplete="new-password" placeholder="输入新密码" />
          <span class="login-field-error" data-error-for="password" hidden>请输入新密码</span>
        </label>
        <label class="login-field" for="loginPasswordConfirm">
          <span class="login-label">确认新密码</span>
          <input class="login-input" id="loginPasswordConfirm" name="password-confirm" type="password" autocomplete="new-password" placeholder="再次输入新密码" />
          <span class="login-field-error" data-error-for="password-confirm" hidden>请再次输入新密码</span>
        </label>
`)
  .replace(rowBlock, '        <div class="login-row"><label class="login-check"><input type="checkbox" name="logout-sessions" value="on" checked /><span>退出其他会话</span></label></div>')
  .replace('进入工作台</span>', '保存新密码</span>')
  .replace(credentials, '')
  .replace('        <p class="login-security-note">', '        <#if isAppInitiatedAction??><button class="login-link" type="submit" name="cancel-aia" value="true" formnovalidate>取消</button></#if>\n        <p class="login-security-note">');
await savePage('login-update-password.ftl', update);
const withoutFields = page => page.replace(accountBlock, '').replace(passwordBlock, '').replace(rowBlock, '').replace(credentials, '');
const withoutSubmit = page => page.replace(/        <button\n[\s\S]*?        <\/button>/, '');
const passive = page => withoutSubmit(withoutFields(page)).replace('<form class="login-card" id="loginForm" action="${url.loginAction}" method="post" novalidate>', '<div class="login-card">').replace('    </form>', '    </div>');
const info = heading(passive(keycloak), '身份中心', '<#if message??>${kcSanitize(message.summary)?no_esc}</#if>')
  .replace(/        <p [^\n]*id="loginFormError"[^\n]+\n/, '')
  .replace('        <p class="login-security-note">', [
    '        <#if !skipLink??>',
    '        <#if pageRedirectUri?has_content><a class="login-link" id="backToApplication" href="${pageRedirectUri}">返回工作台</a>',
    '        <#elseif actionUri?has_content><a class="login-link" id="proceedAction" href="${actionUri}">继续</a>',
    '        <#elseif (client.baseUrl)?has_content><a class="login-link" id="backToApplication" href="${client.baseUrl}">返回工作台</a></#if>',
    '        </#if>',
    '        <p class="login-security-note">',
  ].join('\n'));
await savePage('info.ftl', info);
const error = heading(passive(keycloak), '无法完成登录', '请根据身份中心的提示重试，或联系管理员。')
  .replace('        <p class="login-security-note">', '        <#if traceId??><p class="login-form-desc">${msg("traceIdSupportMessage", traceId)}</p></#if>\n        <#if !skipLink?? && client?? && client.baseUrl?has_content><a class="login-link" id="backToApplication" href="${client.baseUrl}">返回工作台</a></#if>\n        <p class="login-security-note">');
await savePage('error.ftl', error);
await writeFile(new URL('theme.properties', themeRoot), 'parent=keycloak\n');

// Preserve every original CSS declaration/order, including responsive rules and
// all component states. Login uses no italic face; regular Inter is self-hosted.
let css = await readFile(new URL('app.css', source), 'utf8');
css = css.replace(/@font-face\s*\{[^}]*font-style:\s*italic;[^}]*\}\s*/g, '')
  .replace('https://static.linear.app/fonts/InterVariable.woff2?v=4.1', './InterVariable.woff2');
await writeFile(new URL('login.css', publicRoot), '/* Generated from the unmodified references/ui-v1/app.css. */\n' + css);
for (const [from, to] of [
  [new URL('logo.png', source), 'logo.png'],
  ...['admin', 'issues', 'apps'].map(name => [new URL(`preview-shots/login-shot-${name}.png`, source), `login-shot-${name}.png`]),
  [new URL('../apps/portal/public/fonts/InterVariable.woff2', import.meta.url), 'InterVariable.woff2'],
  [new URL('../apps/portal/public/fonts/Inter-LICENSE.txt', import.meta.url), 'Inter-LICENSE.txt'],
]) await copyFile(from, new URL(to, publicRoot));
for (const name of ['login.css', 'login.js', 'theme-init.js', 'login-fx.js', 'logo.png', 'login-shot-admin.png', 'login-shot-issues.png', 'login-shot-apps.png', 'InterVariable.woff2', 'Inter-LICENSE.txt']) {
  await copyFile(new URL(name, publicRoot), new URL(name, resourcesRoot));
}
console.log('Generated fixture login HTML and Keycloak theme from references/ui-v1; shared resource bytes match.');
